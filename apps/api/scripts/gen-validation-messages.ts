// Generates src/lib/validationMessages.ts from Hibernate Validator's bundles
// (org/hibernate/validator/ValidationMessages*.properties in the jar the Java
// API ships, hibernate-validator-8.0.1.Final):
//   unzip -o hibernate-validator-8.0.1.Final.jar 'org/hibernate/validator/ValidationMessages*' -d /tmp/hv
//   bun scripts/gen-validation-messages.ts /tmp/hv/org/hibernate/validator
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const KEYS = ['AssertFalse', 'AssertTrue', 'DecimalMax', 'DecimalMin', 'Email', 'Future', 'FutureOrPresent', 'Max', 'Min', 'Negative',
  'NegativeOrZero', 'NotBlank', 'NotEmpty', 'NotNull', 'Null', 'Past', 'PastOrPresent', 'Pattern', 'Positive', 'PositiveOrZero', 'Size'];
const dir = process.argv[2]!;
const out: Record<string, Record<string, string>> = {};
for (const f of readdirSync(dir).filter((f) => f.startsWith('ValidationMessages') && f.endsWith('.properties')).sort()) {
  const locale = f === 'ValidationMessages.properties' ? '' : f.slice('ValidationMessages_'.length, -'.properties'.length);
  const text = readFileSync(join(dir, f), 'latin1').replace(/\\u([0-9a-fA-F]{4})/g, (_m, h: string) => String.fromCharCode(parseInt(h, 16)));
  const msgs: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    const m = /^jakarta\.validation\.constraints\.(\w+)\.message\s*=\s*(.*)$/.exec(line);
    if (m && KEYS.includes(m[1]!)) msgs[m[1]!] = m[2]!.trim();
  }
  out[locale] = msgs;
}
writeFileSync(join(import.meta.dir, '..', 'src', 'lib', 'validationMessages.ts'),
  `// GENERATED by scripts/gen-validation-messages.ts from hibernate-validator 8.0.1.Final's
// ValidationMessages*.properties (the bundles the Java API uses). Key '' = the base bundle.
// Do not edit by hand.
export const VALIDATION_BUNDLES: Record<string, Partial<Record<string, string>>> = ${JSON.stringify(out, null, 2)};
`);
console.log(`${Object.keys(out).length} bundles`);
