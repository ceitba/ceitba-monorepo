// Splits drizzle-kit's single introspected schema.ts into src/db/schema/<area>.ts.
//   DRIZZLE_DB_URL=postgres://.../db_migrated_with_all_prod_migrations bunx drizzle-kit pull
//   bun scripts/split-schema.ts            (reads drizzle-introspect/schema.ts)
// Tables are assigned to areas by name (AREAS below; unknown -> misc.ts).
// Cross-file references become imports. Hand edits to src/db/schema are lost
// on re-run: put feature-specific helpers in the feature's repo.ts instead.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = join(import.meta.dir, '..', 'drizzle-introspect', 'schema.ts');
const OUT = join(import.meta.dir, '..', 'src', 'db', 'schema');

const AREAS: Record<string, RegExp> = {
  academic: /^(careers|plan|commission|subject|commission_time|plan_subject|plan_section_requirement|plan_entry|plan_entry_override|plan_entry_effective|schedule_correction|schedule_correction_vote|day_of_week|subject_type)$/,
  identity: /^(user|ceitba_staff|ceitba_moderators|api_keys|refresh_tokens|user_devices|deleted_firebase_accounts|capability_settings|capability_user_grants|capability_org_grants|ceitba_branch|ceitba_staff_role|scheduled_job_run|push_log|wiki)$/,
  news: /^(articles|article_votes|vote_records|analytics_events|news_events|organizations|user_follows|event_rsvps|user_organizations|org_invites|home_highlights)$/,
  cms: /^(staff_departments|staff_members|benefits|benefit_cards)$/,
  schedules: /^(saved_schedules|share_sessions|share_session_participants|study_groups|study_group_participants)$/,
  proposals: /^(proposal|proposal_comment|proposal_attachment|proposal_alias|proposal_vote)$/,
  reviews: /^(professor|subject_review|subject_review_professor|subject_review_helpful|subject_review_report)$/,
  mail: /^(digest_issues|digest_issue_links|digest_deliveries|digest_delivery_links|mail_send_log|mail_account_state|mail_tracking_event|mail_sender_account|org_announcements|org_announcement_deliveries|org_mail_optouts)$/,
  wiki: /^(subject_comment|subject_note|career_note|subject_wiki_page|subject_wiki_edit_proposal|subject_comment_vote|subject_note_vote|career_note_vote|Subject_Bookmarks|subject_bookmarks|subject_difficulty|proposal_status|vote_type)$/,
  kb: /^kb_/,
  drive: /^drive_/,
};

// drizzle-kit prints an empty-string default as `.default(')`.
const src = readFileSync(SRC, 'utf8').replaceAll(".default(')", ".default('')");
const importLine = src.split('\n')[0]!;
const blocks: { name: string; table: string; body: string }[] = [];
const re = /^export const (\w+) = ([\w.]+)\("([^"]+)"/;
const lines = src.split('\n');
let cur: { name: string; table: string; body: string[] } | null = null;
for (const line of lines.slice(2)) {
  const m = re.exec(line);
  if (m) {
    if (cur) blocks.push({ ...cur, body: cur.body.join('\n').trimEnd() });
    cur = { name: m[1]!, table: m[3]!, body: [line] };
  } else if (cur) {
    cur.body.push(line);
  }
}
if (cur) blocks.push({ ...cur, body: cur.body.join('\n').trimEnd() });

// drizzle-kit names both wiki."Subject_Bookmarks" and wiki.subject_bookmarks
// subjectBookmarksInWiki; the mixed-case legacy table gets its own name.
for (const b of blocks) {
  if (b.table === 'Subject_Bookmarks') {
    b.body = b.body.replace('export const subjectBookmarksInWiki', 'export const subjectBookmarksLegacyInWiki');
    b.name = 'subjectBookmarksLegacyInWiki';
  }
}

const areaOf = (table: string) => Object.entries(AREAS).find(([, r]) => r.test(table))?.[0] ?? 'misc';
const byArea = new Map<string, typeof blocks>();
const owner = new Map<string, string>();
for (const b of blocks) {
  const a = areaOf(b.table);
  owner.set(b.name, a);
  byArea.set(a, [...(byArea.get(a) ?? []), b]);
}

const coreImports = importLine.replace(/^import \{ /, '').replace(/ \} from .*$/, '').split(', ');
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
const header = '// GENERATED by scripts/split-schema.ts from `drizzle-kit pull` against a database migrated with\n// every production migration (apps/api/src/main/resources/db/migration). Do not edit by hand.\n';
for (const [area, bs] of byArea) {
  const text = bs.map((b) => b.body).join('\n\n');
  const used = coreImports.filter((i) => new RegExp(`(?<![.\\w])${i}[(.]`).test(text));
  const cross = new Map<string, Set<string>>();
  for (const [name, a] of owner) {
    if (a === area) continue;
    if (new RegExp(`(?<![.\\w])${name}[.(]`).test(text)) {
      cross.set(a, (cross.get(a) ?? new Set()).add(name));
    }
  }
  const imports = [
    `import { ${used.join(', ')} } from 'drizzle-orm/pg-core';`,
    /\bsql`/.test(text) ? "import { sql } from 'drizzle-orm';" : '',
    ...[...cross].sort().map(([a, names]) => `import { ${[...names].sort().join(', ')} } from './${a}';`),
  ].filter(Boolean);
  writeFileSync(join(OUT, `${area}.ts`), `${header}${imports.join('\n')}\n\n${text}\n`);
}
const areas = [...byArea.keys()].sort();
writeFileSync(join(OUT, 'index.ts'), `${header}${areas.map((a) => `export * from './${a}';`).join('\n')}\n`);
console.log(`Wrote ${blocks.length} definitions into ${areas.length} files: ${areas.join(', ')}`);
